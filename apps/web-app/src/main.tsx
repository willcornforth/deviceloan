import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import { Auth0Provider } from '@auth0/auth0-react'
import './index.css'
import App from './App.tsx'

const domain = import.meta.env.VITE_AUTH0_DOMAIN
const clientId = import.meta.env.VITE_AUTH0_CLIENT_ID
const audience = import.meta.env.VITE_AUTH0_AUDIENCE

if (!audience) {
  throw new Error('Missing Auth0 audience configuration. Please check your environment variables.')
}

if (!clientId) {
  throw new Error('Missing Auth0 client ID configuration. Please check your environment variables.')
}

if (!domain) {
  throw new Error('Missing Auth0 domain configuration. Please check your environment variables.')
}

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <Auth0Provider
      domain={domain}
      clientId={clientId}
      authorizationParams={{
        redirect_uri: window.location.origin,
        audience: audience,
      }}
    >
      <App />
    </Auth0Provider>
  </StrictMode>,
)
